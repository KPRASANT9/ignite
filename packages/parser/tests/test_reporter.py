# --- Helpers ---

def _make_span(
    span_id: str,
    kind: SpanKind = SpanKind.API_CALL,
    target: str = "",
    method: str | None = None,
    url: str | None = None,
    status_code: int | None = None,
    body_schema: dict | None = None,
    request_body: dict | None = None,
    error: str | None = None,
    what_happened: str = "tested",
    what_learned: str = "learned something",
    confidence: Confidence = Confidence.HIGH,
    questions: list[str] | None = None,
    enables: list[str] | None = None,
    tags: list[str] | None = None,
    sequence: int = 1,
) -> Span:
    return Span(
        span_id=span_id,
        trace_id="trace-1",
        sequence=sequence,
        kind=kind,
        started_at=datetime(2026, 7, 24, 14, 0, tzinfo=timezone.utc),
        interaction=Interaction(
            target=target,
            method=method,
            request=Request(url=url, body=request_body),
            response=Response(status_code=status_code, body_schema=body_schema, error=error),
        ),
        observation=Observation(
            what_happened=what_happened,
            what_learned=what_learned,
            confidence=confidence,
            questions_raised=questions or [],
        ),
        relationships=Relationships(enables=enables or []),
        tags=tags or [],
    )


def _make_finding(
    finding_id: str,
    category: FindingCategory = FindingCategory.PROTOCOL,
    title: str = "Test finding",
    description: str = "A test finding description",
    confidence: FindingConfidence = FindingConfidence.CONFIRMED,
    source_spans: list[str] | None = None,
) -> Finding:
    return Finding(
        finding_id=finding_id,
        trace_id="trace-1",
        source_spans=source_spans or [],
        category=category,
        title=title,
        description=description,
        confidence=confidence,
    )


def _make_trace(
    trace_id: str = "trace-1",
    system: str = "plaid",
    spans: list[Span] | None = None,
    findings: list[Finding] | None = None,
) -> Trace:
    return Trace(
        schema_version="0.1",
        trace_id=trace_id,
        agent_id="TestAgent",
        agent_role=AgentRole.EXPLORER,
        system=system,
        started_at=datetime(2026, 7, 24, 14, 0, tzinfo=timezone.utc),
        status=TraceStatus.COMPLETED,
        objective="Test objective",
        spans=spans or [],
        findings=findings or [],
    )


