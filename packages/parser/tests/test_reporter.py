# --- Integration: fixture file ---

def test_report_from_fixture():
    """Full pipeline: fixture JSON → Parser → Analyzer → Reporter."""
    fixture = FIXTURE_DIR / "valid_trace.json"
    with open(fixture) as f:
        data = json.load(f)

    parse_result = parse_trace(data)
    assert parse_result.ok

    analysis = analyze(parse_result.traces)
    report = generate_report(analysis, title="Plaid Link Study", system="plaid")

    # Verify key content surfaces
    assert "# Plaid Link Study" in report
    assert "**System:** plaid" in report
    assert "POST" in report
    assert "link_token" in report
    assert "4" in report  # 4-hour TTL mentioned somewhere
    assert "Open Questions" in report
    assert "Generated by IGNITE L2 Pipeline" in report
    # Report should be substantial
    assert len(report) > 500
