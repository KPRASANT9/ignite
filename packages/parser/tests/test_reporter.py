def test_findings_sorted_by_confidence():
    f1 = _make_finding("f1", title="Hypothesis finding", confidence=FindingConfidence.HYPOTHESIS)
    f2 = _make_finding("f2", title="Confirmed finding", confidence=FindingConfidence.CONFIRMED)
    trace = _make_trace(findings=[f1, f2])
    result = analyze([trace])
    report = generate_report(result)

    # Confirmed should appear before hypothesis
    confirmed_pos = report.index("Confirmed finding")
    hypothesis_pos = report.index("Hypothesis finding")
    assert confirmed_pos < hypothesis_pos


